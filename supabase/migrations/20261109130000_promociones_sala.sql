-- Promociones de la pantalla de sala de espera.
--
-- La TV de la sala mostraba sólo turnos, y la mayor parte del día se quedaba en
-- "En breve le llamaremos". Mientras no hay llamados pasa en ciclo las imágenes
-- de las promociones vigentes; al llamar un turno lo muestra un rato y regresa.
--
-- Las promociones cambian cada mes, así que no viven en el código: se suben
-- desde Configuración > Promociones sala, con su orden, si están activas y,
-- opcionalmente, desde y hasta qué día se muestran. Así la del mes siguiente se
-- puede dejar programada y la vencida deja de salir sola.

create table if not exists public.promociones_sala (
	id_promocion bigint generated by default as identity primary key,
	titulo text,
	storage_path text not null,
	orden integer not null default 0,
	activa boolean not null default true,
	vigente_desde date,
	vigente_hasta date,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	constraint promociones_sala_vigencia_check
		check (vigente_desde is null or vigente_hasta is null or vigente_desde <= vigente_hasta)
);

comment on table public.promociones_sala is 'Imágenes de promociones que la pantalla de sala de espera pasa en ciclo entre turnos.';
comment on column public.promociones_sala.storage_path is 'Ruta de la imagen dentro del bucket promociones-sala.';
comment on column public.promociones_sala.vigente_desde is 'Primer día en que se muestra; nulo = desde ya.';
comment on column public.promociones_sala.vigente_hasta is 'Último día en que se muestra; nulo = sin fecha de fin.';

create index if not exists idx_promociones_sala_orden
	on public.promociones_sala (activa, orden);

create or replace function public.set_promociones_sala_updated_at()
returns trigger
language plpgsql
as $$
begin
	new.updated_at = now();
	return new;
end;
$$;

drop trigger if exists trg_promociones_sala_updated_at on public.promociones_sala;
create trigger trg_promociones_sala_updated_at
	before update on public.promociones_sala
	for each row
	execute function public.set_promociones_sala_updated_at();

-- La pantalla de la sala no inicia sesión: lee las promociones como anónima.
-- Sólo el personal con sesión las da de alta, las cambia o las borra.
alter table public.promociones_sala enable row level security;

drop policy if exists promociones_sala_select on public.promociones_sala;
create policy promociones_sala_select
on public.promociones_sala
for select to anon, authenticated
	using (true);

drop policy if exists promociones_sala_insert on public.promociones_sala;
create policy promociones_sala_insert
on public.promociones_sala
for insert to authenticated
	with check (true);

drop policy if exists promociones_sala_update on public.promociones_sala;
create policy promociones_sala_update
on public.promociones_sala
for update to authenticated
	using (true)
	with check (true);

drop policy if exists promociones_sala_delete on public.promociones_sala;
create policy promociones_sala_delete
on public.promociones_sala
for delete to authenticated
	using (true);

grant select on public.promociones_sala to anon, authenticated;
grant insert, update, delete on public.promociones_sala to authenticated;

-- La TV se entera al momento de una promoción nueva o desactivada.
do $$
begin
	if not exists (
		select 1
		from pg_publication_tables
		where pubname = 'supabase_realtime'
			and schemaname = 'public'
			and tablename = 'promociones_sala'
	) then
		alter publication supabase_realtime add table public.promociones_sala;
	end if;
exception
	when undefined_object then
		null;
end;
$$;

-- Las imágenes son publicidad pensada para verse en la sala: el bucket es
-- público y la pantalla las carga por su URL sin sesión. Subir, reemplazar y
-- borrar sí pide sesión.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
	'promociones-sala',
	'promociones-sala',
	true,
	10 * 1024 * 1024,
	array['image/png', 'image/jpeg', 'image/webp']
)
on conflict (id) do update
set
	public = true,
	file_size_limit = excluded.file_size_limit,
	allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists promociones_sala_storage_select on storage.objects;
create policy promociones_sala_storage_select
on storage.objects
for select to anon, authenticated
	using (bucket_id = 'promociones-sala');

drop policy if exists promociones_sala_storage_insert on storage.objects;
create policy promociones_sala_storage_insert
on storage.objects
for insert to authenticated
	with check (bucket_id = 'promociones-sala');

drop policy if exists promociones_sala_storage_update on storage.objects;
create policy promociones_sala_storage_update
on storage.objects
for update to authenticated
	using (bucket_id = 'promociones-sala')
	with check (bucket_id = 'promociones-sala');

drop policy if exists promociones_sala_storage_delete on storage.objects;
create policy promociones_sala_storage_delete
on storage.objects
for delete to authenticated
	using (bucket_id = 'promociones-sala');

